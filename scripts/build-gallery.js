#!/usr/bin/env node
"use strict";

// Regenerates docs/gallery/ from the sample flows in examples/ and test/fixtures/.
// Every page is produced by the same CLI commands users run, so the gallery
// always shows real output.
//
//   node scripts/build-gallery.js          write the gallery
//   node scripts/build-gallery.js --check  exit 1 if the committed gallery is out of date

const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");

const ROOT = path.join(__dirname, "..");
const CLI = path.join(ROOT, "cli", "studio-flow-check.js");
const OUT = path.join(ROOT, "docs", "gallery");

const EXAMPLES = [
  {
    slug: "main-inbound",
    title: "Main inbound line (example)",
    file: "examples/main-inbound-example.xml",
    blurb: "The sample script that ships with the viewer: hours check, menu, CRM lookup and queue routing.",
  },
  {
    slug: "broken-flow",
    title: "A flow with problems",
    file: "test/fixtures/broken-flow.xml",
    lib: ["test/fixtures/PostCallSurvey.xml"],
    blurb: "A deliberately broken script: an unreachable step, a loop with no exit, a menu with no timeout and a missing target.",
  },
  {
    slug: "reference-check",
    title: "CXone reference-list check",
    file: "test/fixtures/reference-flow.xml",
    refs: { skills: "test/fixtures/skills.csv", hours: "test/fixtures/hours.csv", scripts: "test/fixtures/scripts.csv" },
    blurb: "Skill, hours-profile and script names checked against exported CXone lists.",
  },
];

const VERSIONS = {
  slug: "version-diff",
  title: "Comparing two versions",
  old: "test/fixtures/flow-v1.xml",
  new: "test/fixtures/flow-v2.xml",
  blurb: "A changed greeting and a new promo step, as the diff command reports them.",
};

function cli(args) {
  const res = spawnSync(process.execPath, [CLI, ...args], { cwd: ROOT, encoding: "utf8" });
  if (res.status === 2) throw new Error(`studio-flow-check ${args.join(" ")} failed: ${res.stderr || res.stdout}`);
  return res.stdout;
}

function fence(lang, text) {
  return "```" + lang + "\n" + text.replace(/\s+$/, "") + "\n```\n";
}

function pageFor(ex) {
  const refArgs = ex.refs ? ["--skills", ex.refs.skills, "--hours", ex.refs.hours, "--scripts", ex.refs.scripts] : [];
  const libArgs = (ex.lib || []).flatMap(l => ["--lib", l]);
  const check = cli(["check", "--fail-on", "never", ...refArgs, ...libArgs, ex.file]);
  const tests = cli(["tests", ...libArgs, ex.file]);
  const mermaid = cli(["mermaid", ex.file]);
  return [
    `# ${ex.title}`,
    "",
    ex.blurb,
    "",
    `Source: \`${ex.file}\``,
    "",
    "## QA check",
    "",
    fence("text", check),
    "## Test cases (CSV)",
    "",
    "The first rows of the CSV export. Open the full file with `studio-flow-check tests` to see every row.",
    "",
    fence("csv", tests.split(/\r?\n/).slice(0, 4).join("\n")),
    "## Flowchart (Mermaid)",
    "",
    "Paste this into any Mermaid-aware viewer to draw the flow.",
    "",
    fence("mermaid", mermaid),
  ].join("\n");
}

function versionPage() {
  const diff = cli(["diff", VERSIONS.old, VERSIONS.new]);
  return [
    `# ${VERSIONS.title}`,
    "",
    VERSIONS.blurb,
    "",
    `Old: \`${VERSIONS.old}\`  New: \`${VERSIONS.new}\``,
    "",
    fence("text", diff),
  ].join("\n");
}

function indexPage(pages) {
  const rows = pages.map(p => `- [${p.title}](${p.slug}.md): ${p.blurb}`);
  return [
    "# Example gallery",
    "",
    "These pages are generated by `node scripts/build-gallery.js` from the sample files in this repository. Each one shows the output of a command-line tool, so you can see what it produces before you run it on your own scripts.",
    "",
    ...rows,
    "",
  ].join("\n");
}

function build() {
  const pages = [...EXAMPLES, VERSIONS].map(p => ({ slug: p.slug, title: p.title, blurb: p.blurb }));
  const outputs = new Map();
  for (const ex of EXAMPLES) outputs.set(`${ex.slug}.md`, pageFor(ex));
  outputs.set(`${VERSIONS.slug}.md`, versionPage());
  outputs.set("README.md", indexPage(pages));
  return outputs;
}

function main() {
  const check = process.argv.includes("--check");
  const outputs = build();
  if (check) {
    const stale = [];
    for (const [name, text] of outputs) {
      const file = path.join(OUT, name);
      if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) stale.push(name);
    }
    if (stale.length) {
      process.stderr.write(`Gallery is out of date: ${stale.join(", ")}. Run node scripts/build-gallery.js.\n`);
      process.exit(1);
    }
    process.stdout.write("Gallery is up to date.\n");
    process.exit(0);
  }
  fs.mkdirSync(OUT, { recursive: true });
  for (const [name, text] of outputs) fs.writeFileSync(path.join(OUT, name), text, "utf8");
  process.stdout.write(`Wrote ${outputs.size} pages to docs/gallery/.\n`);
}

main();
